"""Generate display-only decompositions of Arabic contextual presentation forms."""

import unicodedata
from pathlib import Path


def main() -> None:
    forms = []
    text = []
    for cp in (*range(0xFB50, 0xFE00), *range(0xFE70, 0xFF00)):
        decomposition = unicodedata.decomposition(chr(cp))
        if decomposition.startswith(('<isolated>', '<initial>', '<medial>', '<final>')):
            normalized = tuple(map(ord, unicodedata.normalize('NFKC', chr(cp))))
            forms.append((cp, len(text), len(normalized)))
            text.extend(normalized)
    lines = [
        '// Generated by gen/arabic_presentation_forms.py; do not edit.',
        f'// Unicode {unicodedata.unidata_version}. License: GPLv3.',
        '#pragma once',
        'static const char_type arabic_presentation_text[] = {',
    ]
    for start in range(0, len(text), 12):
        lines.append('    ' + ', '.join(f'0x{cp:x}' for cp in text[start : start + 12]) + ',')
    lines.extend(('};', 'static const struct { char_type cp; uint16_t offset; uint8_t count; } arabic_presentation_forms[] = {'))
    lines.extend(f'    {{0x{cp:x}, {offset}, {count}}},' for cp, offset, count in forms)
    lines.extend(('};', ''))
    Path(__file__).resolve().parents[1].joinpath('kitty/arabic-presentation-forms.h').write_text('\n'.join(lines))


if __name__ == '__main__':
    main()
